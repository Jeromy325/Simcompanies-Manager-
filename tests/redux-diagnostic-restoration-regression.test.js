'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'dashboard.html'), 'utf8');
const dashboard = fs.readFileSync(path.join(root, 'dashboard.js'), 'utf8');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'manifest.json'), 'utf8'));
assert.equal(manifest.version, '2.5.351');
assert.match(html, /id="downloadReduxStoreDump"/, 'Redux diagnostic download control is present');
assert.match(dashboard, /querySelector\('#downloadReduxStoreDump'\)/, 'Redux download click handler is present');
assert.match(dashboard, /sendGameTabMessage\(tab\.id,\{type:'RUN_REDUX_STATE_DIAGNOSTIC'/, 'Redux capture uses content-script recovery');
assert.match(dashboard, /RUN_REDUX_STATE_DIAGNOSTIC/, 'dashboard requests state diagnostic through content bridge');
assert.match(dashboard, /simcompanies-runtime-state-access-/, 'capture downloads a diagnostic JSON file');
assert.match(dashboard, /page-hook-request/, 'records bridge request result');
assert.match(dashboard, /No content-script response within/, 'bridge has explicit timeout and failure report');
const pageHook = fs.readFileSync(path.join(root, 'page-hook.js'), 'utf8');
const content = fs.readFileSync(path.join(root, 'content.js'), 'utf8');
assert.match(pageHook, /collectStateAccessDiagnostic/, 'page hook owns bounded state collector');
assert.match(pageHook, /REDUX_STATE_DIAGNOSTIC_GET/, 'page hook handles state diagnostic request');
assert.match(content, /pendingReduxDiagnostics/, 'content bridge correlates diagnostic request IDs');
assert.match(content, /REDUX_STATE_DIAGNOSTIC_RESULT/, 'content bridge returns page-hook diagnostic result');
assert.match(dashboard, /tab-selection/,'reports tab selection stage');
assert.match(dashboard, /page-hook-request/,'reports page-hook bridge stage');
assert.match(dashboard, /simcompanies-redux-capture-failure-/,'downloads failure report instead of losing diagnostic details');
assert.match(dashboard, /discovery-result/,'records state-discovery result stage');
console.log('redux-diagnostic-restoration-regression: 8 assertions passed');
