'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const dashboard = fs.readFileSync(path.join(root, 'dashboard.js'), 'utf8');
const html = fs.readFileSync(path.join(root, 'dashboard.html'), 'utf8');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'manifest.json'), 'utf8'));
assert.equal(manifest.version, '2.5.349');
assert.match(dashboard, /function plannerHistoryAuditExport\(\)/, 'per-building audit can be exported');
assert.match(dashboard, /matchedCurrentCycle/, 'audit records whether current history matched');
assert.match(dashboard, /historyRequestStatus/, 'audit records history request status');
assert.match(dashboard, /selectedRateSource/, 'audit records selected rate source');
assert.match(dashboard, /fallbackReason/, 'audit records fallback reason');
assert.match(dashboard, /active cycle amount \u00f7 duration \(measured game rate\)/, 'active-cycle quantity and duration are available as a measured-rate fallback');
assert.match(dashboard, /do not apply modifiers a second time/, 'measured active-cycle rates avoid double-applying production modifiers');
assert.match(dashboard, /result\?\.ok\?'success'/, 'request success/failure response is recorded');
assert.match(dashboard, /productionHistoryAudit:plannerHistoryAuditExport\(\)/, 'diagnostic bundle includes history audit');
