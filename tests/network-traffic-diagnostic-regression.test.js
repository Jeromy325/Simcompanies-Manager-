const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const pageHook = fs.readFileSync(path.join(root, 'page-hook.js'), 'utf8');
const content = fs.readFileSync(path.join(root, 'content.js'), 'utf8');
const background = fs.readFileSync(path.join(root, 'background.js'), 'utf8');
const html = fs.readFileSync(path.join(root, 'dashboard.html'), 'utf8');
const dashboard = fs.readFileSync(path.join(root, 'dashboard.js'), 'utf8');
assert.match(pageHook, /SET_NETWORK_CAPTURE/, 'page hook supports opt-in capture control');
assert.match(pageHook, /NETWORK_CAPTURE_MAX_BODY/, 'API response bodies are bounded');
assert.match(pageHook, /safeNetworkUrl/, 'capture restricts to same-origin URLs and redacts sensitive query keys');
assert.match(pageHook, /response\.clone\(\)/, 'fetch response body capture does not consume the game response');
assert.match(content, /NETWORK_CAPTURE_EVENT/, 'content bridge forwards captured events');
assert.match(content, /pendingNetworkControl/, 'capture control waits for a page-hook acknowledgement');
assert.match(content, /waitForHookReady\(3500\)/, 'capture control checks the game-page hook is ready');
assert.match(content, /NETWORK_CAPTURE_CONTROL_ACK/, 'content bridge resolves capture control only on hook acknowledgement');
assert.match(background, /scmNetworkTrafficCapture/, 'background stores a bounded diagnostic record');
assert.match(background, /3500000/, 'stored capture has a byte ceiling');
assert.match(html, /startNetworkCapture/, 'diagnostic page has a capture control');
assert.match(html, /downloadNetworkCapture/, 'diagnostic page has a network JSON export control');
assert.match(dashboard, /simcompanies-manager-network-capture-v3-/, 'export uses a unique Network Capture 3.0 filename');
assert.match(dashboard, /networkCaptureStatus/,'shows live capture status and event counts');
assert.match(dashboard, /waitForNetworkCaptureQuiet/,'waits for event writes to settle before export');
assert.match(dashboard, /countsMatch/,'verifies event count before export');
assert.match(dashboard, /waitForNetworkCaptureStarted/, 'dashboard requires a persisted start marker before reporting active capture');
assert.match(dashboard, /status==='recording'/, 'dashboard checks persisted recorder status');
assert.match(pageHook, /kind:'request-error'/,'records request errors');
assert.match(background, /safeEvent.kind==='capture-start'/,'starts a clean capture session rather than appending stale events');
console.log('Network traffic diagnostic regression checks passed.');
