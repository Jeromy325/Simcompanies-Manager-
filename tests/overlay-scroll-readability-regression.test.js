'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const content = fs.readFileSync(path.join(root, 'content.js'), 'utf8');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'manifest.json'), 'utf8'));
assert.equal(manifest.version, '2.5.382');
const start = content.indexOf("st.id='scm-game-overlay-style'");
const end = content.indexOf("(document.head||document.documentElement).appendChild(st)", start);
assert.ok(start >= 0 && end > start, 'overlay stylesheet must exist');
const css = content.slice(start, end);
assert.match(css, /#scm-game-balance-card[^}]*max-height:48vh;overflow-y:auto;overflow-x:hidden/, 'outer card is the single scroll container');
assert.match(css, /\.scm-go-grid\{[^}]*max-height:none;overflow:visible/, 'inner resource list must not create a nested scrollbar');
assert.match(css, /\.scm-go-stock,\.scm-go-contract,\.scm-go-remaining\{[^}]*font-size:11px/, 'desktop values use readable 11px text');
assert.match(css, /\.scm-go-name\{font-size:13px;font-weight:400/, 'resource names are larger and regular weight');
assert.match(css, /\.scm-go-title,\.scm-ch-title\{font-size:13px;font-weight:400/, 'overlay headings are larger and regular weight');
assert.match(css, /@media\(max-width:700px\)[\s\S]*\.scm-go-stock,\.scm-go-contract,\.scm-go-remaining\{font-size:12px;line-height:1.3/, 'mobile values remain readable');
console.log('Overlay scroll/readability regression checks passed.');
