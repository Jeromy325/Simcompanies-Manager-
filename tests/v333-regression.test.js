// 2.5.333: notifications (test button + production-finished alerts from the game's busy.started + busy.duration).
const assert = require('assert');
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const read = f => fs.readFileSync(path.join(root, f), 'utf8');
const manifest = JSON.parse(read('manifest.json'));
assert.equal(manifest.version, '2.5.393');
assert.ok(manifest.permissions.includes('notifications'), 'notifications permission');
const bg = read('background.js');
const fnSrc = bg.slice(bg.indexOf('function productionFinishAlarms('), bg.indexOf('async function scheduleProductionFinishAlarms('));
const productionFinishAlarms = new Function(fnSrc + 'return productionFinishAlarms;')();
const started = '2026-10-23T10:34:00Z', dur = 58380;
const out = productionFinishAlarms(1, [{ id: 9001, busy: { started, duration: dur } }, { id: 9002 }, { id: 9003, busy: { started: 'bad', duration: 10 } }]);
assert.equal(out.length, 1, 'only buildings with a running batch');
assert.equal(out[0].when, Date.parse(started) + dur * 1000, 'finish = started + duration (seconds)');
assert.equal(out[0].name, `scm-prodfin:1:9001:${Date.parse(started) + dur * 1000}`);
assert.ok(bg.includes('scheduleProductionFinishAlarms(targetRealm,rows)'), 'scheduled whenever buildings are captured');
assert.ok(bg.includes("type==='SCM_TEST_NOTIFICATION'") && bg.includes("type==='SCM_NOTIFY_SETTINGS'"));
assert.ok(bg.includes("startsWith('scm-prodfin:')"), 'own alarm prefix, separate from scm-building- manual alarms');
const sched = bg.slice(bg.indexOf('async function scheduleProductionFinishAlarms('), bg.indexOf('async function fireProductionFinished('));
assert.ok(!/pageGet|fetch\(/.test(sched), 'no network work');
const dash = read('dashboard.js'), html = read('dashboard.html');
assert.ok(html.includes('id="notifyTest"') && html.includes('data-nf="productionFinished"'));
assert.ok(dash.includes("type:'SCM_TEST_NOTIFICATION'"));
console.log('v333-regression: all assertions passed');
