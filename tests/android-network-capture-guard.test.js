const fs = require('fs');
const path = require('path');
const assert = require('assert');
const root = path.resolve(__dirname, '..');
const js = fs.readFileSync(path.join(root, 'dashboard.js'), 'utf8');
const html = fs.readFileSync(path.join(root, 'dashboard.html'), 'utf8');
const hook = fs.readFileSync(path.join(root, 'page-hook.js'), 'utf8');
const bg = fs.readFileSync(path.join(root, 'background.js'), 'utf8');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'manifest.json'), 'utf8'));
assert.match(js, /networkCaptureUnsupportedOnAndroid=\/Android\/i.test\(navigator\.userAgent/);
assert.match(js, /SCM_MOBILE_NET_START/);
assert.match(js, /SCM_MOBILE_NET_STOP/);
assert.doesNotMatch(js, /networkCaptureUnsupportedOnAndroid&&networkCaptureButton\)\{networkCaptureButton\.disabled=true/);
assert.match(html, /page-level fetch\/XHR capture on Android/);
assert.match(hook, /NETWORK_CAPTURE_MAX_EVENTS=100000, NETWORK_CAPTURE_MAX_BODY=4000/);
assert.match(bg, /scmMobileNetSave/);
assert.match(bg, /SCM_MOBILE_NET_START/);
assert.match(bg, /scmMobileNetLogBackground/);
assert.match(bg, /extension-background/);
assert.equal(manifest.version, '2.5.339');
console.log('Android overnight network capture regression checks passed.');
